/**
 * Reads a WebP file's width and height from its header, so the API can check uploads without
 * decoding the image (architecture.md 8.1: the backend re-validates every upload). Returns null if
 * the bytes aren't a WebP image.
 */
export function webpSize(b: Uint8Array): { width: number; height: number } | null {
  const text = (i: number, n: number) => String.fromCharCode(...b.subarray(i, i + n));
  if (b.length < 30 || text(0, 4) !== "RIFF" || text(8, 4) !== "WEBP") return null;
  const chunk = text(12, 4);
  if (chunk === "VP8 ") {
    return { width: (b[26]! | (b[27]! << 8)) & 0x3fff, height: (b[28]! | (b[29]! << 8)) & 0x3fff };
  }
  if (chunk === "VP8L") {
    const bits = b[21]! | (b[22]! << 8) | (b[23]! << 16) | (b[24]! << 24);
    return { width: (bits & 0x3fff) + 1, height: ((bits >>> 14) & 0x3fff) + 1 };
  }
  if (chunk === "VP8X") {
    return {
      width: 1 + (b[24]! | (b[25]! << 8) | (b[26]! << 16)),
      height: 1 + (b[27]! | (b[28]! << 8) | (b[29]! << 16)),
    };
  }
  return null;
}
