// Copies the exact logo SVGs from brand/cke-logo-package into a TypeScript module,
// so the apps can render them with react-native-svg. The logo is never redrawn.
// Run: npm run logos --workspace @cke/brand-tokens
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const svgDir = join(here, "../../../brand/cke-logo-package/logo/svg");
const files = {
  logoHorizontalCream: "cke-logo-horizontal-cream.svg",
  logoHorizontalCharcoal: "cke-logo-horizontal-charcoal.svg",
  iconCream: "cke-icon-cream.svg",
  iconCharcoal: "cke-icon-charcoal.svg",
};

let out = "// Generated by scripts/build-logos.mjs from brand/cke-logo-package. Do not edit.\n\n";
for (const [name, file] of Object.entries(files)) {
  const svg = readFileSync(join(svgDir, file), "utf8").trim();
  const vb = svg.match(/viewBox="([\d.\s-]+)"/)?.[1].split(/\s+/).map(Number) ?? [0, 0, 1, 1];
  out += `export const ${name} = { xml: ${JSON.stringify(svg)}, ratio: ${(vb[2] / vb[3]).toFixed(4)} };\n`;
}
writeFileSync(join(here, "../src/logos.generated.ts"), out);
console.log("Wrote src/logos.generated.ts");
